from __future__ import annotations

from typing import Any, Protocol, runtime_checkable


@runtime_checkable
class BackendProtocol(Protocol):
    def get_app(self, *, app_slug: str) -> dict[str, Any] | None: ...
    def ensure_app(self, *, app_slug: str, display_name: str, source_system: str, external_app_id: str | None) -> dict[str, Any]: ...
    def update_app(self, app_id: str, **changes: Any) -> dict[str, Any]: ...
    def get_export(self, *, app_id: str, version_label: str) -> dict[str, Any] | None: ...
    def get_active_export(self, *, app_id: str) -> dict[str, Any] | None: ...
    def list_exports(self, *, app_id: str) -> list[dict[str, Any]]: ...
    def list_export_rows(self, *, table: str, export_id: str) -> list[dict[str, Any]]: ...
    def count_export_rows(self, *, table: str, export_id: str) -> int: ...
    def count_search_documents(self, *, export_id: str) -> int: ...
    def count_pending_search_document_embeddings(self, *, export_id: str) -> int: ...
    def list_pending_search_document_embedding_inputs(
        self,
        *,
        export_id: str,
        limit: int,
        offset: int | None = None,
    ) -> list[dict[str, Any]]: ...
    def create_export(self, payload: dict[str, Any]) -> dict[str, Any]: ...
    def update_export(self, export_id: str, **changes: Any) -> dict[str, Any]: ...
    def delete_export_scoped_rows(self, table: str, export_id: str) -> None: ...
    def upsert_rows(self, table: str, rows: list[dict[str, Any]]) -> None: ...
    def append_export_source_evidence_batch(self, *, export_id: str, rows: list[dict[str, Any]]) -> None: ...
    def append_export_entities_batch(self, *, export_id: str, rows: list[dict[str, Any]]) -> None: ...
    def append_export_edges_batch(self, *, export_id: str, rows: list[dict[str, Any]]) -> None: ...
    def append_export_entity_facets_batch(self, *, export_id: str, rows: list[dict[str, Any]]) -> None: ...
    def append_export_overlay_links_batch(self, *, export_id: str, rows: list[dict[str, Any]]) -> None: ...
    def append_export_public_api_workflow_index_batch(self, *, export_id: str, rows: list[dict[str, Any]]) -> None: ...
    def append_export_permission_surface_index_batch(self, *, export_id: str, rows: list[dict[str, Any]]) -> None: ...
    def upload_object(self, *, bucket: str, object_path: str, payload: bytes) -> None: ...
    def download_object(self, *, bucket: str, object_path: str) -> bytes: ...
    def replace_search_documents(self, *, export_id: str, documents: list[dict[str, Any]], associations: list[dict[str, Any]]) -> None: ...
    def persist_search_document_embeddings(self, *, export_id: str, embeddings: list[dict[str, Any]]) -> None: ...
    def cutover_replace_active_export(self, *, app_id: str, replacement_export_id: str) -> dict[str, Any]: ...
    def activate_export(self, *, app_id: str, target_export_id: str) -> dict[str, Any]: ...
    def archive_export(self, *, app_id: str, target_export_id: str) -> dict[str, Any]: ...
    def archive_app(self, *, app_id: str) -> dict[str, Any]: ...
    def insert_lifecycle_action(self, payload: dict[str, Any]) -> dict[str, Any]: ...
    def update_lifecycle_action(self, action_id: str, **changes: Any) -> dict[str, Any]: ...
    def list_source_evidence_rows(self, *, export_id: str) -> list[dict[str, Any]]: ...
    def delete_object(self, *, bucket: str, object_path: str) -> None: ...
    def delete_export(self, *, export_id: str) -> None: ...
    def prepare_app_for_delete(self, *, app_id: str) -> dict[str, Any]: ...
    def finalize_delete_app(self, *, app_id: str, keep_lifecycle_action_id: str | None = None) -> None: ...
    def delete_export_legacy(self, *, export_id: str) -> None: ...
    def delete_app(self, *, app_id: str) -> None: ...
    def delete_export_for_app_delete(self, *, app_id: str, export_id: str) -> None: ...
    def list_source_evidence_hashes(self, *, export_id: str, evidence_role: str) -> list[str]: ...
    def search_entities(self, *, app_slug: str, query_text: str, search_mode: str, limit: int, export_id: str | None, query_embedding: list[float] | None, allow_archived_app: bool) -> dict[str, Any]: ...
    def get_entity(self, *, app_slug: str, entity_lookup: str, export_id: str | None, allow_archived_app: bool) -> dict[str, Any]: ...
    def get_neighbors(self, *, app_slug: str, entity_key: str, direction: str, relation_filter: str | None, limit: int, export_id: str | None, allow_archived_app: bool) -> dict[str, Any]: ...
    def find_paths(self, *, app_slug: str, from_anchor: str, to_anchor: str, direction: str, relation_filter: str | None, max_hops: int, max_paths: int, export_id: str | None, allow_archived_app: bool) -> dict[str, Any]: ...
    def build_context_bundle(self, *, app_slug: str, export_id: str | None, query_text: str | None, entity_key: str | None, search_mode: str, anchor_limit: int, max_hops: int, entity_limit: int, edge_limit: int, query_embedding: list[float] | None, allow_archived_app: bool) -> dict[str, Any]: ...
    def get_public_api_workflows(self, *, app_slug: str, export_id: str | None, requires_auth: bool | None, accepts_request_data: bool | None, workflow_name: str | None, allow_archived_app: bool) -> dict[str, Any]: ...
    def get_pipeline_run_status(
        self,
        *,
        pipeline_run_id: str | None = None,
        app_slug: str | None = None,
        export_id: str | None = None,
        version_label: str | None = None,
    ) -> dict[str, Any]: ...
    def request_pipeline_run_action(self, *, pipeline_run_id: str, requested_action: str) -> dict[str, Any]: ...
    def enqueue_embedding_job(
        self,
        *,
        app_slug: str,
        version_label: str,
        initial_limit: int,
        min_limit: int,
        max_attempts: int | None = None,
    ) -> dict[str, Any]: ...
    def get_embedding_job_status(
        self,
        *,
        job_id: str | None = None,
        app_slug: str | None = None,
        export_id: str | None = None,
        version_label: str | None = None,
    ) -> dict[str, Any]: ...
    def request_embedding_job_action(self, *, job_id: str, requested_action: str) -> dict[str, Any]: ...
